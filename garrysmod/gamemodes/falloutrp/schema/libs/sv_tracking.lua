local function WrapMoney()
	local characterMeta = ix.meta.character

	if (not characterMeta) then return false end

	--[[
		`SetMoney` is GENERATED by `ix.char.RegisterVar("money")` rather than
		written out, so it exists only once that has run. At schema load it
		normally already has - but "normally" is not a guarantee worth a silent
		hole in the money log, so this returns false and is retried.
	]]
	local original = characterMeta.SetMoney

	if (not original) then return false end

	--[[
		Wrapped once. The guard is what stops a `lua_refresh` wrapping the
		wrapper around itself and logging every change twice - which reads as
		two people moving money rather than one.
	]]
	if (characterMeta.ixTracked) then return true end

	characterMeta.ixTracked = true

	function characterMeta:SetMoney(amount)
		local before = self:GetMoney() or 0

		original(self, amount)

		local after = self:GetMoney() or 0

		if (before == after) then return end

		ix.log.Add(self:GetPlayer(), "moneyChange", self:GetName(),
			self:GetID(), before, after, after - before,
			ix.tracking.reason or "unknown")
	end

	return true
end

if (not WrapMoney()) then
	hook.Add("InitializedPlugins", "ixTrackingMoney", function()
		if (not WrapMoney()) then
			ErrorNoHalt("[falloutrp] character SetMoney never appeared - "
				.. "money changes are NOT being logged\n")
		end
	end)
end

ix.log.AddType("moneyChange", function(client, name, charID, before, after,
	delta, reason)
	return string.format(
		"%s (char %d) %s %s - %s to %s [%s]%s", name, charID,
		delta > 0 and "gained" or "lost",
		ix.currency.Get(math.abs(delta)), ix.currency.Get(before),
		ix.currency.Get(after), reason,
		IsValid(client) and (" " .. client:SteamID()) or "")
end, FLAG_WARNING)

