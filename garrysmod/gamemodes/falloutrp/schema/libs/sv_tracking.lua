--[[
	Logging the things that get argued about.

	Helix registers exactly ONE log type of its own - `charMoneyGive` - so a
	server running it has no record of who picked up what, who dropped what,
	who moved money, or what anybody said. Every question an admin actually
	gets asked is about one of those.

	    every money change      with the before, the after and the reason
	    every item transfer     between which two inventories, and whose
	    every item spawned      and every item picked up off the floor
	    every weapon drawn
	    every chat line
	    every connect, character load and death

	MONEY IS WRAPPED, NOT HOOKED, because there is no hook. `SetMoney` is the
	single funnel every path goes through - a shop sale, a `/givemoney`, a
	salary, an admin's `/charsetmoney` - so wrapping it once catches all of
	them, including ones written later that nobody remembered to log.

	THE REASON IS INFERRED FROM WHAT ELSE IS HAPPENING, and that is a
	deliberate limit rather than a guess dressed up: `ix.tracking.reason` is
	set for the duration of an operation that knows why it is moving money and
	cleared afterwards. Anything that does not set it is logged as "unknown",
	which is honest and still tells you the amount, the character and the time.
]]

if (not SERVER) then return end

ix.tracking = ix.tracking or {}

--[[
	Why money is moving right now, if anything knows.

	A single value rather than a stack: money moves synchronously inside one
	operation, so there is never a second reason waiting behind the first.
]]
ix.tracking.reason = nil

--- Run something with a reason attached, and clear it however that ends.
function ix.tracking.With(reason, callback)
	ix.tracking.reason = reason

	local ok, err = pcall(callback)

	ix.tracking.reason = nil

	if (not ok) then error(err) end
end

