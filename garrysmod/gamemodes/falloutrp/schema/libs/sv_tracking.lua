--[[
	Naming an inventory in a way an admin can act on.

	An inventory id alone is a number nobody can look up later. Whose it is, or
	what container it belongs to, is the thing that turns "item 4471 moved from
	12 to 88" into "Bob gave it to Alice".

	`ix.item.inventories[0]` IS A BARE TABLE, NOT AN INVENTORY.

	Helix uses index 0 to mean "the world" and stores a plain `{}` there - no
	metatable, so no `GetOwner`, no `GetID`, no anything. This called
	`inventory:GetOwner()` straight out and threw on every single transfer that
	touched the world, which is every item picked up off the ground and every
	item dropped onto it.

	AND THE THROW WAS THE REAL DAMAGE. `OnItemTransferred` is fired from inside
	`ITEM:Transfer`, which is inside the take function, which is inside
	`ix.item.PerformInventoryAction` - and an error in a hook takes all three
	down with it. The item had already been added to its new inventory by then;
	what never ran was the rest of `Transfer`, the `return true`, and

	    if (result != false) then
	        if (IsValid(entity)) then entity.ixIsSafe = true entity:Remove()

	which is what removes the entity from the ground. So a picked-up item was
	in the inventory AND still lying there, pressing E on it a second time
	answered "same inv", and dropping it hit `item.entity:GetPos()` on an
	entity that had since been removed. Three unrelated-looking faults from one
	unguarded method call in a LOG LINE.

	Nothing that only writes a log entry may ever be able to do that, so this
	answers "the world" for anything without the methods rather than assuming
	it has them.
]]
local function Describe(inventory)
	if (not inventory or not inventory.GetID) then return "the world" end

	local owner = inventory.GetOwner and inventory:GetOwner()
	local vars = inventory.vars or {}

	--[[
		A PACK BY NAME. A pack's storage belongs to the character carrying
		it, so the owner test below called it the character, and a stimpak
		put into a pack "moved from <character> to <character>".
	]]
	if (isstring(vars.isBag) and ix.backpack and ix.backpack.ItemOf) then
		local pack = ix.backpack.ItemOf(inventory)

		if (pack) then
			local held = IsValid(owner) and owner:IsPlayer() and owner:GetCharacter()

			return string.format("the %s (item %d)%s", pack:GetName(), pack.id,
				held and string.format(" of %s (char %d)", owner:Name(), held:GetID()) or "")
		end
	end

	if (IsValid(owner) and owner:IsPlayer()) then
		local character = owner:GetCharacter()

		return string.format("%s (char %d)", owner:Name(),
			character and character:GetID() or 0)
	end

	if (vars.bench) then
		return string.format("bench %d", vars.bench)
	end

	if (vars.factionStorage) then
		return string.format("faction storage %d", vars.factionStorage)
	end

	if (vars.trash) then
		return string.format("the bin of char %d", vars.trash)
	end

	return string.format("inventory %d", inventory:GetID() or 0)
end

--[[
	The whole hook, wrapped so a log line can never break a transfer again.

	The bug above was one nil call; the LESSON is that anything hanging off
	`OnItemTransferred` runs inside somebody else's transaction. A `pcall` here
	costs nothing measurable and turns "the log line was wrong" back into what
	it should always have been: a wrong log line.
]]
local function Safely(fn, ...)
	local ok, err = pcall(fn, ...)

	if (not ok) then
		ErrorNoHalt(string.format("[falloutrp] item tracking failed, and the "
			.. "transfer carried on regardless: %s\n", tostring(err)))
	end
end

--[[
	EVERY transfer, including the ones inside one inventory.

	Moving an item from one slot to another is not interesting on its own, so
	it is skipped - but a transfer BETWEEN inventories is the single most
	useful line in the whole log, because it is what item laundering looks
	like.
]]
hook.Add("OnItemTransferred", "ixTracking", function(item, from, to)
	if (from == to) then return end

	Safely(function()
		local client = item.player

		if (not IsValid(client) and to) then
			local owner = to.GetOwner and to:GetOwner()

			if (IsValid(owner) and owner:IsPlayer()) then client = owner end
		end

		ix.log.Add(client, "itemMove", item.name, item.id, item.uniqueID,
			Describe(from), Describe(to), ix.stack.Get(item))
	end)
end)

ix.log.AddType("itemMove", function(client, name, id, uniqueID, from, to,
	quantity)
	return string.format("%s (item %d, %s)%s moved from %s to %s%s", name, id,
		uniqueID, quantity > 1 and (" x" .. quantity) or "", from, to,
		IsValid(client) and (" - by " .. client:Name()) or "")
end)

hook.Add("OnItemSpawned", "ixTracking", function(entity)
	local item = entity.GetItemTable and entity:GetItemTable()

	if (not item) then return end

	ix.log.Add(nil, "itemWorld", item.name, item.id, item.uniqueID,
		tostring(entity:GetPos()))
end)

ix.log.AddType("itemWorld", function(client, name, id, uniqueID, position)
	return string.format("%s (item %d, %s) is now on the ground at %s", name,
		id, uniqueID, position)
end)

--[[
	Equipping is logged from the WEAPON CHANGING, not from
	`CanPlayerEquipItem`.

	That hook lives inside the item function's `OnCanRun`, which Helix calls
	every time it builds a right-click menu - so logging there would write a
	line every time anybody looked at a gun, and a log that is mostly noise is
	a log nobody reads. `PlayerWeaponChanged` fires when something actually
	happened.
]]
hook.Add("PlayerWeaponChanged", "ixTracking", function(client, weapon)
	if (not IsValid(weapon)) then return end

	local item = weapon.ixItem

	ix.log.Add(client, "weaponDrawn", weapon:GetClass(),
		item and item.name or weapon:GetPrintName() or "",
		item and item.id or 0)
end)

ix.log.AddType("weaponDrawn", function(client, class, name, id)
	return string.format("%s drew %s%s.", client:Name(),
		name ~= "" and name or class,
		id > 0 and string.format(" (item %d)", id) or "")
end)

