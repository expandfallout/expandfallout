hook.Add("PostPlayerSay", "ixTracking", function(client, text, chatType)
	ix.log.Add(client, "chatLine", chatType or "ic", text)
end)

ix.log.AddType("chatLine", function(client, chatType, text)
	return string.format("[%s] %s: %s", chatType, client:Name(), text)
end)

--[[
	CHARACTER LOADS, CREATIONS, DELETIONS, DEATHS, CONNECTS AND DISCONNECTS
	ARE NOT LOGGED HERE, and it is worth writing down why not.

	Helix's own `plugins/logging.lua` already registers `charLoad`,
	`charCreate`, `charDelete`, `playerDeath`, `connect` and `disconnect`.
	Registering a type that already exists REPLACES its formatter - so ours
	took over, and then Helix's plugin called it with ITS arguments:

	    ix.log.Add(client, "charLoad", character:GetName())   -- one argument
	    function(client, name, id, steamID) ... "%d" ... id   -- three expected

	which is `bad argument #4 to 'text' (number expected, got nil)` on every
	character load, from inside `character:Setup()`.

	Their versions cover the same ground. Everything else in this file logs
	something nothing else does, which is the only reason for any of it to
	exist - see the collision guard in `sv_adminlog.lua`.
]]
